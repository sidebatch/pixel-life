// Pack only new AI rod art; do not regenerate existing character atlases/tools.
import fs from 'node:fs';
import vm from 'node:vm';
import {alphaBounds,blank,blitNearest,crop,decodePNG,encodePNG} from './lib/png.mjs';
const rigFile='src/data/character-rig-data.js',source=fs.readFileSync(rigFile,'utf8'),context={};
vm.createContext(context);vm.runInContext(source+';globalThis.rig=CHARACTER_RIG;',context);
const rig=JSON.parse(JSON.stringify(context.rig));
const write=(file,image)=>fs.writeFileSync(file,encodePNG(image));
const boundsAndPack=image=>{
  const b=alphaBounds(image),out=blank(96,96),scale=Math.min(80/b.width,80/b.height);
  const w=Math.round(b.width*scale),h=Math.round(b.height*scale),dx=Math.round((96-w)/2),dy=Math.round((96-h)/2);
  blitNearest(out,crop(image,b.x,b.y,b.width,b.height),dx,dy,w,h);return {out,dx,dy,w,h};
};
for(const id of ['tidal','tempest','abyssal','aurora']){
  const image=decodePNG(fs.readFileSync(`assets/fishing/source/rods/${id}.png`));
  if(!image.data.some((v,p)=>p%4===3&&v===0))throw new Error('Source must have genuine alpha: '+id);
  write(`assets/fishing/rods/${id}.png`,boundsAndPack(image).out);
  // Same line clipping rule as the production rig packer. The actual fishing
  // line is drawn from the tip at runtime; no extra line hangs over the player.
  for(let y=0;y<image.height;y++)for(let x=0;x<image.width;x++)
    if(x+y>image.width*1.19&&x>image.width*.62)image.data[(y*image.width+x)*4+3]=0;
  const {out,dx,dy,w,h}=boundsAndPack(image),grip=[dx+Math.round(w*.15),dy+Math.round(h*.85)],tip=[dx+Math.round(w*.97),dy+Math.round(h*.03)];
  write(`assets/player/rig-v1/tools/rod-${id}.png`,out);
  rig.tools['rod.'+id]={grip,tip,nativeAngle:Math.atan2(tip[1]-grip[1],tip[0]-grip[0]),nativeLength:Math.hypot(tip[0]-grip[0],tip[1]-grip[1])};
}
fs.writeFileSync(rigFile,`// Generated by scripts/pack-npc-character.mjs. Source rig-v1 preserved.\n// New rod tools packed by scripts/pack-fishing-rod-expansion.mjs.\nconst CHARACTER_RIG=Object.freeze(${JSON.stringify(rig,null,2)});\n`);
console.log('Packed four new 96px rod icons and tools; all old geometry/art/anchors preserved.');
